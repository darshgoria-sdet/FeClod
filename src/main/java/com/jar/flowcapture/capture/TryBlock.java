package com.jar.flowcapture.capture;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import lombok.Data;

import java.util.UUID;

/**
 * A run of steps the generated test wraps in try/catch.
 *
 * The case it exists for is the optional screen: a coupon sheet, a permission prompt, a
 * "rate us" dialog that shows on some runs and not others. Without this the only honest
 * options are to record two flows or to let the test fail on a dialog nobody cares about.
 * The repo already handles these by hand — HandlingBottomSheets is nothing but try/catch
 * around dismissals — so this generates the shape that is already house style.
 *
 * Blocks are identified by id and steps point at them, rather than the block holding a pair
 * of indexes. Indexes move the moment a step is inserted or deleted, and a try block that
 * silently slides onto the wrong steps would be worse than not having one.
 */
@JsonIgnoreProperties(ignoreUnknown = true)
@Data
public class TryBlock {

    public enum OnFailure {
        /**
         * Log it and carry on — the steps were optional. The generated catch matches the
         * repo's own idiom: log.info(message) then log.info(e.getMessage()).
         */
        CONTINUE,
        /**
         * Still fail, but say why in the flow's own words. Useful where a failure is real but
         * the raw Appium message ("no such element") tells a reviewer nothing about intent.
         */
        FAIL_WITH_MESSAGE,
        /**
         * Run a different set of steps instead — the catch as a backup route.
         *
         * This is how the team already uses try/catch by hand: if the first way through a
         * screen does not work, try the other way. The recovery steps are ordinary recorded
         * steps, tagged to this block's catch rather than its try, so they are recorded,
         * replayed and generated by exactly the same machinery as everything else.
         */
        RUN_RECOVERY_STEPS
    }

    private String id = UUID.randomUUID().toString();
    private OnFailure onFailure = OnFailure.CONTINUE;

    /** Why these steps are wrapped, in the author's words — becomes the logged/thrown message. */
    private String note;
}
